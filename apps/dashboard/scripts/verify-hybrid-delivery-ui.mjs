import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";
import assert from "node:assert/strict";
import { chromium } from "playwright";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const dashboard = path.join(root, "apps/dashboard");
const requireDashboard = createRequire(path.join(dashboard, "package.json"));
const { createServer } = await import(pathToFileURL(requireDashboard.resolve("vite")).href);
const name = `hybrid-delivery-qa-${Date.now()}`;
const htmlPath = path.join(dashboard, `${name}.html`);
const entryPath = path.join(dashboard, `${name}.tsx`);
let server, browser;
try {
  await fs.writeFile(htmlPath, `<html lang="pt-BR"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head><body><div id="root"></div><script type="module" src="/${name}.tsx"></script></body></html>`);
  await fs.writeFile(entryPath, `import React from 'react';
import {createRoot} from 'react-dom/client';
import {DeliveryPage} from './src/pages/delivery/DeliveryPage';
import {WhatsAppSellerPage} from './src/pages/whatsapp-seller/WhatsAppSellerPage';
import {StepWhatsApp} from './src/pages/onboarding-wizard/steps/StepWhatsApp';
import {FunnelPage} from './src/pages/funnel/FunnelPage';
import {ApiContext} from './src/hooks/useApi';
import './src/styles.css';
import './src/pages/onboarding-wizard/onboarding-wizard.css';
const config={melhorEnvioEnabled:false,melhorEnvioConnected:true,melhorEnvioExpiresAt:null,originZip:'01001000',ownDelivery:{enabled:true,mode:'fixed',flatPriceCents:800,freeAboveCents:null,estimatedValue:60,estimatedUnit:'minutes',neighborhoods:[],radiusZones:[]}};
window.__updates=[];
window.__funnelQueries=[];
const api={getDeliveryConfig:async()=>config,getShipments:async()=>({items:[],total:0}),updateDeliveryConfig:async payload=>{window.__updates.push(payload);return {success:true}},getWhatsAppConfig:async()=>({enabled:true,provider:'meta',status:'active',whatsappNumber:'5511998765432'}),getWhatsAppOnboarding:async()=>({configured:false}),getWhatsAppUsage:async()=>null};
Object.assign(api,{getStorefrontFunnel:async(_id,params)=>{window.__funnelQueries.push(params);return {steps:[],transitions:[],bottleneck:null,totalSessions:0,overallConversion:0,period:{from:'2026-10-01',to:'2026-10-23'}}},getStorefrontFunnelSessions:async()=>({sessions:[],total:0})});
const merchant={id:'qa',name:'Loja de teste'} as never;
const surface=new URLSearchParams(location.search).get('surface');
createRoot(document.getElementById('root')).render(<ApiContext.Provider value={api as never}><main className="dashboard-ui" style={{padding:24,maxWidth:1200,margin:'auto'}}>{surface==='funnel'?<FunnelPage apiBaseUrl="http://mock.invalid" me={merchant}/>:surface==='whatsapp'?<WhatsAppSellerPage apiBaseUrl="http://mock.invalid" me={merchant}/>:surface==='onboarding'?<StepWhatsApp me={merchant}/>:<DeliveryPage apiBaseUrl="http://mock.invalid" me={merchant}/>}</main></ApiContext.Provider>);`);
  server = await createServer({ root: dashboard, server: { host: "127.0.0.1", port: 0, open: false } });
  await server.listen();
  const address = server.httpServer.address();
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  page.setDefaultTimeout(60000);
  page.setDefaultNavigationTimeout(60000);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${address.port}/${name}.html`, { waitUntil: "domcontentloaded" });
  const switches = page.getByRole("switch");
  await switches.nth(0).waitFor();
  assert.equal(await switches.nth(1).getAttribute("aria-checked"), "true");
  await switches.nth(0).click();
  await page.waitForFunction(() => window.__updates.length === 1);
  assert.equal(await switches.nth(0).getAttribute("aria-checked"), "true");
  assert.equal(await switches.nth(1).getAttribute("aria-checked"), "true");
  assert.deepEqual(await page.evaluate(() => window.__updates[0]), { melhorEnvioEnabled: true });
  await page.getByRole("button", { name: "Configurar", exact: true }).click();
  assert.equal(await page.getByLabel("CEP de origem", { exact: true }).inputValue(), "01001-000");
  await page.getByLabel("CEP de origem", { exact: true }).fill("01002000");
  assert.equal(await page.getByLabel("CEP de origem", { exact: true }).inputValue(), "01002-000");
  await page.getByLabel("Preço da entrega (R$)", { exact: true }).fill("123456");
  assert.equal(await page.getByLabel("Preço da entrega (R$)", { exact: true }).inputValue(), "1.234,56");
  await page.getByLabel("Preço da entrega (R$)", { exact: true }).fill("1200");
  assert.equal(await page.getByLabel("Preço da entrega (R$)", { exact: true }).inputValue(), "12,00");
  await page.getByLabel("Entrega grátis a partir de (R$)", { exact: true }).fill("25000");
  assert.equal(await page.getByLabel("Entrega grátis a partir de (R$)", { exact: true }).inputValue(), "250,00");
  await page.getByRole("button", { name: "Salvar e ativar", exact: true }).click();
  await page.waitForFunction(() => window.__updates.length === 2);
  const saved = await page.evaluate(() => window.__updates[1]);
  assert.equal(saved.ownDelivery.flatPriceCents, 1200);
  assert.equal(saved.ownDelivery.freeAboveCents, 25000);
  assert.equal(saved.originZip, "01002000");
  assert.equal(Object.hasOwn(saved, "melhorEnvioEnabled"), false);
  assert.equal(await switches.nth(0).getAttribute("aria-checked"), "true");
  assert.equal(await switches.nth(1).getAttribute("aria-checked"), "true");
  const desktop = path.join(os.tmpdir(), "zyon-hybrid-delivery-desktop.png");
  await page.screenshot({ path: desktop, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Configurar", exact: true }).click();
  await page.getByRole("dialog").evaluate(async dialog => { await Promise.all(dialog.getAnimations().map(animation => animation.finished)); });
  const mobile = path.join(os.tmpdir(), "zyon-hybrid-delivery-mobile.png");
  await page.screenshot({ path: mobile, fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  const whatsappScreenshots = {};
  for (const surface of ["whatsapp", "onboarding"]) {
    await page.goto(`http://127.0.0.1:${address.port}/${name}.html?surface=${surface}`, { waitUntil: "domcontentloaded" });
    await page.getByText(surface === "whatsapp" ? "+55 (11) 99876-5432" : "Número +55 (11) 99876-5432", { exact: true }).waitFor();
    const glyph = page.locator('svg image').first();
    await glyph.waitFor({ state: "attached" });
    const glyphLoaded = await glyph.evaluate(async element => {
      const img = new Image(); img.src = element.getAttribute('href'); await img.decode(); return img.naturalWidth > 0;
    });
    assert.equal(glyphLoaded, true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    whatsappScreenshots[surface] = path.join(os.tmpdir(), `zyon-${surface}-formatted-mobile.png`);
    await page.screenshot({ path: whatsappScreenshots[surface], fullPage: true });
  }
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(`http://127.0.0.1:${address.port}/${name}.html?surface=funnel`, { waitUntil: "domcontentloaded" });
  const from = page.getByLabel("Data inicial", { exact: true });
  const to = page.getByLabel("Data final", { exact: true });
  await from.waitFor();
  for (const width of [1280, 960]) {
    await page.setViewportSize({ width, height: 900 });
    const preset = await page.getByRole("button", { name: "Hoje", exact: true }).boundingBox();
    const date = await from.boundingBox();
    if (width === 1280) {
      const segment = await page.getByLabel("Segmentar resultados").boundingBox();
      assert.ok(Math.abs(preset.y - date.y) < 2, "desktop presets and dates must share a row");
      assert.ok(Math.abs(date.y - segment.y) < 2, "desktop segmentation must share the date row");
    } else {
      assert.ok(date.y >= preset.y, "wrapped dates must follow the presets");
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    }
    assert.ok(date.width < 200, "date inputs must stay compact");
  }
  await from.fill("2026-10-01");
  await to.fill("2026-10-23");
  await page.getByLabel("Segmentar resultados").selectOption("device");
  await page.getByLabel("Comparar com o período anterior").check();
  await page.waitForFunction(() => window.__funnelQueries.some(q => q.from === "2026-10-01" && q.to === "2026-10-23" && q.breakdown === "device" && q.compare === true));
  await page.getByRole("button", { name: "30 dias", exact: true }).click();
  assert.equal(await from.inputValue(), "");
  assert.equal(await to.inputValue(), "");
  await page.getByRole("button", { name: "Limpar filtros adicionais", exact: true }).click();
  await page.setViewportSize({ width: 1280, height: 900 });
  const funnelDesktop = path.join(os.tmpdir(), "zyon-funnel-filters-desktop.png");
  await page.screenshot({ path: funnelDesktop, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  const funnelMobile = path.join(os.tmpdir(), "zyon-funnel-filters-mobile.png");
  await page.locator(".funnel-query").screenshot({ path: funnelMobile });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ checks: ["independent activation", "CEP and BRL input masks", "local price and origin saved", "both methods remain enabled", "WhatsApp and onboarding phone formatting", "official WhatsApp glyph loaded", "compact funnel dates align with presets", "funnel dates, segmentation and comparison still submit", "mobile has no horizontal overflow", "no browser errors"], screenshots: { desktop, mobile, ...whatsappScreenshots, funnelDesktop, funnelMobile } }));
} finally {
  await browser?.close();
  await server?.close();
  await fs.rm(htmlPath, { force: true });
  await fs.rm(entryPath, { force: true });
}
