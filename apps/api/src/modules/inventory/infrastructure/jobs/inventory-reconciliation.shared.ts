import type { RedisOptions } from "ioredis";

/** Shared BullMQ queue name + Redis connection for the reconciliation scheduler/worker. */
export const INVENTORY_RECONCILIATION_QUEUE = "inventory-reconciliation";

export function inventoryReconciliationRedisConnection(): RedisOptions | null {
  const raw = process.env.REDIS_URL?.trim();
  if (!raw) return null;
  const url = new URL(raw);
  return {
    host: url.hostname,
    port: url.port ? Number(url.port) : 6379,
    username: url.username ? decodeURIComponent(url.username) : undefined,
    password: url.password ? decodeURIComponent(url.password) : undefined,
    db: url.pathname.length > 1 ? Number(url.pathname.slice(1)) : 0,
    maxRetriesPerRequest: null,
  };
}
