import { test } from "node:test";
import assert from "node:assert/strict";
import { respondToCashbackCommand } from "./cashback-whatsapp.commands.js";

test("VERIFIER CB-13 WhatsApp can apply the monetary amount generated by its own high-value quick reply", async () => {
  const q = { merchantId: "m", sessionId: "s", eligible: true, programActive: true, reason: null, availableCents: 150000,
    maximumRedeemCents: 123456, reservedCents: 0, estimatedEarnCents: 0, ruleVersion: 1, fingerprint: "f", terms: "t" };
  let reserved = 0;
  const ops = { quoteCheckout: async () => q, reserveCheckout: async (_scope: any, amount: number) => {
    reserved = amount; return { ...q, reservedCents: amount };
  }, releaseReservation: async () => q };
  const s = { merchantId: "m", sessionId: "s", globalUserId: "buyer" } as any;
  const choice = await respondToCashbackCommand(ops, s, "Usar cashback", "message-choose");
  assert.equal(choice?.quickReplies[0], "Usar R$ 1.234,56 de cashback");
  const confirmation = await respondToCashbackCommand(ops, s, choice!.quickReplies[0], "message-confirm");
  assert.equal(reserved, 123456);
  assert.match(confirmation!.agentMessage, /aplicados a este pedido/);
});
