import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { chromium } from "playwright";
import { fileURLToPath } from "node:url";
import { createSupportFixture } from "./platform-support-fixture.js";

const fixture = await createSupportFixture();
const browser = await chromium.launch({ headless: true });
const output = new URL("../../../.audit/platform-support-20261018/", import.meta.url);
await mkdir(output, { recursive: true });
const errors: string[] = [];
const debugPages: Array<import("playwright").Page> = [];
const failures: Array<{ status: number; path: string }> = [];
try {
  const merchantContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await merchantContext.addCookies([{ name: "aacp_access_token", value: fixture.merchants.growth!.token, url: fixture.first.url, httpOnly: true, sameSite: "Lax" }]);
  await merchantContext.addInitScript(data => sessionStorage.setItem("support.fixture", JSON.stringify(data)), { api: fixture.first.url + "/v1", merchantId: fixture.merchants.growth!.id });
  const operatorContext = await browser.newContext({ viewport: { width: 1600, height: 1100 } });
  const operator = fixture.operators.support!;
  await operatorContext.addInitScript(data => sessionStorage.setItem("zyon.platform-control.session.v1", JSON.stringify(data)), { token: operator.token, operator: { operator_id: operator.id, email: operator.email, role: operator.role } });
  const merchant = await merchantContext.newPage();
  const admin = await operatorContext.newPage();
  debugPages.push(merchant, admin);
  for (const page of [merchant, admin]) {
    page.on("pageerror", error => errors.push(error.message));
    page.on("response", response => { if (!response.ok() && response.url().includes("platform-support")) failures.push({ status: response.status(), path: new URL(response.url()).pathname }); });
  }
  await Promise.all([merchant.goto("http://127.0.0.1:15441/e2e/fixtures/platform-support.html"), admin.goto("http://127.0.0.1:15442")]);
  await admin.getByRole("button", { name: "Atendimento técnico", exact: true }).click();
  await merchant.getByRole("button", { name: "Ajuda e feedback sobre a Zyon", exact: true }).click();
  await merchant.getByRole("button", { name: "Abrir chamado", exact: true }).click();
  await merchant.getByLabel("Assunto", { exact: true }).fill("Erro real ao publicar o produto");
  await merchant.getByLabel("O que aconteceu?", { exact: true }).fill("Cadastrei um produto e recebi um erro na publicação. Preciso de orientação técnica.");
  await merchant.getByRole("button", { name: "Abrir chamado", exact: true }).last().click();
  await admin.getByRole("button", { name: /Erro real ao publicar o produto/ }).click();
  await operatorContext.grantPermissions(["clipboard-read", "clipboard-write"]);
  await admin.getByRole("button", { name: "Copiar protocolo", exact: true }).click();
  assert.equal(await admin.evaluate(() => navigator.clipboard.readText()), await admin.locator(".ps-protocol-code").textContent());
  const publicReply = "Recebemos seu chamado e estamos verificando a publicação do produto.";
  await admin.getByLabel("Resposta ao cliente", { exact: true }).fill(publicReply);
  await admin.getByRole("button", { name: "Enviar mensagem", exact: true }).click();
  await merchant.locator(".ps-message-body").filter({ hasText: publicReply }).waitFor({ timeout: 15_000 });
  const internal = "Investigar o rastreamento interno deste erro antes de responder.";
  await admin.getByLabel("Nota interna", { exact: true }).fill(internal);
  await admin.getByRole("button", { name: "Salvar nota interna", exact: true }).click();
  await admin.locator(".ps-note p").filter({ hasText: internal }).waitFor();
  await admin.getByRole("checkbox", { name: "Meus atendimentos", exact: true }).check();
  assert.equal(await admin.getByRole("checkbox", { name: "Meus atendimentos", exact: true }).isChecked(), true);
  await admin.getByRole("button", { name: /Erro real ao publicar o produto/ }).waitFor();
  assert.equal(await merchant.getByText(internal, { exact: true }).count(), 0);
  await admin.screenshot({ path: new URL("admin-desktop.png", output).pathname.replace(/^\/(\w:)/, "$1"), fullPage: true });
  await merchant.screenshot({ path: new URL("merchant-desktop.png", output).pathname.replace(/^\/(\w:)/, "$1"), fullPage: true });
  await merchantContext.setOffline(true);
  const recovery = "A resposta continua salva mesmo quando sua conexão cai.";
  await admin.getByLabel("Resposta ao cliente", { exact: true }).fill(recovery);
  await admin.getByRole("button", { name: "Enviar mensagem", exact: true }).click();
  await admin.locator(".ps-message-body").filter({ hasText: recovery }).waitFor();
  await merchantContext.setOffline(false);
  await merchant.locator(".ps-message-body").filter({ hasText: recovery }).waitFor({ timeout: 20_000 });
  await merchant.reload();
  await merchant.getByRole("button", { name: /Ajuda e feedback/ }).click();
  await merchant.getByRole("button", { name: /Erro real ao publicar o produto/ }).click();
  await merchant.locator(".ps-message-body").filter({ hasText: recovery }).waitFor();
  await merchant.setViewportSize({ width: 390, height: 844 });
  await merchant.screenshot({ path: new URL("merchant-mobile.png", output).pathname.replace(/^\/(\w:)/, "$1"), fullPage: true });
  const noOverflow = await merchant.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth);
  assert.equal(noOverflow, true, "mobile page overflow");
  await merchant.keyboard.press("Escape");
  assert.equal(await merchant.getByRole("dialog").count(), 0);
  const tickets = await fixture.prisma.platformSupportTicket.findMany({ where: { merchantId: fixture.merchants.growth!.id } });
  assert.equal(tickets.length, 1);
  assert.equal(await fixture.prisma.platformSupportMessage.count({ where: { ticketId: tickets[0]!.id } }), 3);
  assert.deepEqual(errors, []);
  await writeFile(new URL("browser-evidence.json", output), JSON.stringify({ environment: "isolated local PostgreSQL and Redis", interfaces: "production support components and Control shell", browsers: 2, websocketDelivery: true, reconnectRecovery: true, reloadPersistence: true, privateNotesIsolated: true, protocolCopy: true, ownAssignmentsFilter: true, mobileOverflow: false, keyboardEscape: true, persistedTickets: 1, persistedMessages: 3, browserErrors: errors, productionVerified: false }, null, 2));
  console.log("Two-browser support flow passed: real persistence, live reply, private notes, reconnection, reload, mobile and keyboard.");
} catch (error) {
  for (let i = 0; i < debugPages.length; i++) await debugPages[i]!.screenshot({ path: fileURLToPath(new URL(`failure-${i}.png`, output)), fullPage: true });
  console.log(JSON.stringify({ errors, failures, screens: await Promise.all(debugPages.map(async page => (await page.locator("body").innerText()).slice(-2200))) }));
  throw error;
} finally { await browser.close(); await fixture.close(); }
